// Helper to generate past ISO dates relative to now
const daysAgo = (days: number, hours = 0, mins = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(d.getHours() - hours);
  d.setMinutes(d.getMinutes() - mins);
  return d.toISOString();
};

